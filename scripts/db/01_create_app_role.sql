-- Первоначальная настройка нового окружения PostgreSQL.
-- Выполнять под администратором до запуска приложения и миграций Flyway.
-- Если роль tg_bot_app уже создана, этот файл повторно выполнять не требуется:
-- повторный CREATE ROLE завершится ошибкой о существующей роли.
--
-- Порядок настройки:
-- 1. Выполнить этот файл, например через Query Tool администратора в pgAdmin.
-- 2. В PowerShell открыть psql:
--    docker compose exec bot_db psql -U tg_bot_admin -d tg_bot
-- 3. Внутри psql задать пароль интерактивной командой:
--    \password tg_bot_app
-- 4. Выйти из psql командой \q.
-- 5. Передать пароль приложению через BOT_DB_APP_PASSWORD.
--    Для локальной разработки используется исключённый из Git файл .env.
-- 6. Запустить приложение: Flyway создаст таблицу через V1 и выдаст права через V2.
--
-- LOGIN разрешает использовать роль при подключении.
-- Права на таблицу выдаёт миграция V2__grant_google_connections_permissions.sql.
-- Сам пароль в этот файл не добавлять.
-- Папка scripts/db не выполняется автоматически ни Flyway, ни Docker Compose.

CREATE ROLE tg_bot_app WITH LOGIN;
